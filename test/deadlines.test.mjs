// 기한 평가 사례. 날짜마다 손으로 센 값과 근거 조문을 맞춘다.
import test from "node:test";
import assert from "node:assert/strict";
import { 기한계산, 다음마감, 정렬 } from "../src/engine/deadlines.mjs";
import { 유형확인 } from "../src/engine/classify.mjs";
import { 조문 } from "../src/engine/law.mjs";

const 대출사기 = 유형확인({ 까닭: "대출", 방법: "계좌" });
const 거래사기 = 유형확인({ 까닭: "물건", 방법: "계좌" });
const 하나 = (목록, id) => 목록.find((k) => k.id === id);
const 계산 = (유형, events, 조건 = {}, 오늘 = "2026-10-09") => 기한계산(유형, events, 조건, 오늘);

const 사례 = [
  // [이름, 유형, 날짜, 규칙, 기대 날짜]
  ["불송치 10월 7일 통지", 거래사기, { 불송치통지일: "2026-10-07" }, "불송치이의", "2027-01-07"],
  ["불송치 10월 31일 통지, 끝날이 일요일", 거래사기, { 불송치통지일: "2026-10-31" }, "불송치이의", "2027-02-01"],
  ["불송치 11월 30일 통지, 끝날이 일요일이고 다음 날이 삼일절", 거래사기, { 불송치통지일: "2026-11-30" }, "불송치이의", "2027-03-02"],
  ["불송치 11월 29일 통지, 2월에 해당하는 날이 없음", 거래사기, { 불송치통지일: "2026-11-29" }, "불송치이의", "2027-03-02"],
  ["불송치 12월 20일 통지, 끝날이 토요일", 거래사기, { 불송치통지일: "2026-12-20" }, "불송치이의", "2027-03-22"],
  ["불기소 10월 2일 통지, 30일째가 일요일", 거래사기, { 불기소통지일: "2026-10-02" }, "항고", "2026-11-02"],
  ["불기소 11월 25일 통지, 30일째가 기독탄신일", 거래사기, { 불기소통지일: "2026-11-25" }, "항고", "2026-12-28"],
  ["항고 기각 10월 7일 통지", 거래사기, { 항고기각통지일: "2026-10-07" }, "재정신청", "2026-10-19"],
  ["전화 신청 10월 2일, 연휴를 건너뛴 3영업일", 대출사기, { 구술신청일: "2026-10-02" }, "서면신청", "2026-10-08"],
  ["추가 기한 10월 8일 통지, 14일째가 목요일", 대출사기, { 구술신청일: "2026-10-02", 추가기한통지일: "2026-10-08" }, "추가기한", "2026-10-22"],
  ["채권소멸 공고 10월 16일", 대출사기, { 공고일: "2026-10-16" }, "채권소멸", "2026-12-17"],
  ["채권소멸 공고 10월 16일, 환급 결정", 대출사기, { 공고일: "2026-10-16" }, "환급결정", "2026-12-31"],
  ["고소 10월 5일, 수사 지연 이의", 거래사기, { 고소일: "2026-10-05" }, "수사지연이의", "2027-04-06"],
];

for (const [이름, 유형, events, id, 기대] of 사례) {
  test(`평가 사례: ${이름}`, () => {
    const k = 하나(계산(유형, events), id);
    assert.equal(k.상태, "계산됨", k.메모.join(" "));
    assert.equal(k.날짜, 기대);
    assert.ok(k.계산.length >= 2, "계산 과정이 비어 있다");
  });
}

test("개편 시행일 전에 받은 불송치 통지는 확인 필요로 둔다", () => {
  const k = 하나(계산(거래사기, { 불송치통지일: "2026-09-30" }), "불송치이의");
  assert.equal(k.상태, "확인 필요");
  assert.equal(k.날짜, null);
  assert.match(k.메모[0], /부칙/);
});

test("항고 근거는 통지 날짜에 따라 검찰청법과 공소청법으로 갈린다", () => {
  assert.deepEqual(하나(계산(거래사기, { 불기소통지일: "2026-10-01" }), "항고").근거, ["검찰청법-10", "형소법-66"]);
  assert.deepEqual(하나(계산(거래사기, { 불기소통지일: "2026-10-02" }), "항고").근거, ["공소청법-57", "형소법-66"]);
});

test("서면 신청서를 냈으면 서면 신청 기한은 해당 없음이고, 늦게 냈으면 알린다", () => {
  const 제때 = 하나(계산(대출사기, { 구술신청일: "2026-10-02", 서면제출일: "2026-10-07" }), "서면신청");
  assert.equal(제때.상태, "해당 없음");
  assert.doesNotMatch(제때.메모[0], /늦게/);
  const 늦게 = 하나(계산(대출사기, { 구술신청일: "2026-10-02", 서면제출일: "2026-10-12" }), "서면신청");
  assert.match(늦게.메모[0], /늦게/);
});

test("수사 결과 통지를 받으면 수사 지연 이의는 해당 없음이다", () => {
  const k = 하나(계산(거래사기, { 고소일: "2026-10-05", 송치통지일: "2026-11-02" }), "수사지연이의");
  assert.equal(k.상태, "해당 없음");
});

test("친족 사기는 고소 기간을 계산하고, 2024년 6월 27일 전 범죄는 확인 필요로 둔다", () => {
  const 조건 = { 친족: "예" };
  assert.equal(하나(계산(거래사기, { 범인안날: "2026-10-07" }, 조건), "친족고소").날짜, "2027-04-07");
  assert.equal(하나(계산(거래사기, { 범인안날: "2026-10-07", 송금일: "2024-06-01" }, 조건), "친족고소").상태, "확인 필요");
  assert.equal(하나(계산(거래사기, { 범인안날: "2026-10-07" }, { 친족: "아니오" }), "친족고소").상태, "해당 없음");
});

test("상대방이 친족인지 모르면 친족이라고 보고 계산하고 그렇게 밝힌다", () => {
  const k = 하나(계산(거래사기, { 범인안날: "2026-10-07" }, { 친족: "모름" }), "친족고소");
  assert.equal(k.날짜, "2027-04-07");
  assert.match(k.메모[0], /확실하지 않아/);
  assert.match(하나(계산(거래사기, {}, { 친족: "모름" }), "친족고소").메모[0], /확실하지 않아/);
});

test("제헌절과 노동절이 끝날에 걸리면 다음 날로 넘긴다", () => {
  // 불기소 통지 2026-06-17: 30일째 2026-07-17 은 제헌절, 그다음은 토요일과 일요일
  assert.equal(하나(계산(거래사기, { 불기소통지일: "2026-06-17" }), "항고").날짜, "2026-07-20");
});

test("물건값 사기에는 은행 피해구제 기한이 없다", () => {
  const 목록 = 계산(거래사기, { 송금일: "2026-10-02" });
  for (const id of ["서면신청", "추가기한", "채권소멸", "환급결정"]) assert.equal(하나(목록, id), undefined, id);
});

test("현금으로 건넨 보이스피싱에는 은행 피해구제 기한이 없다", () => {
  const 목록 = 계산(유형확인({ 까닭: "요구", 방법: "현금" }), {});
  assert.equal(하나(목록, "서면신청"), undefined);
  assert.ok(하나(목록, "불송치이의"));
});

test("범위 밖 유형과 고르지 않은 유형은 기한을 내지 않는다", () => {
  assert.deepEqual(계산(유형확인({ 까닭: "투자", 방법: "계좌" }), {}), []);
  assert.deepEqual(계산(유형확인({}), {}), []);
});

test("잘못된 날짜는 무시한다", () => {
  const k = 하나(계산(거래사기, { 불송치통지일: "2026-02-30" }), "불송치이의");
  assert.equal(k.상태, "해당 없음");
});

test("남은 날을 세고, 다음 마감은 지나지 않은 마감 가운데 가장 가까운 것이다", () => {
  const 목록 = 계산(대출사기, { 구술신청일: "2026-10-02", 불송치통지일: "2026-10-07", 공고일: "2026-10-16" });
  assert.equal(하나(목록, "서면신청").남은날, -1);
  assert.equal(하나(목록, "불송치이의").남은날, 90);
  assert.equal(다음마감(목록).id, "불송치이의"); // 채권소멸은 예상일이라 마감이 아니다
  const 순서 = 정렬(목록).filter((k) => k.날짜).map((k) => k.날짜);
  assert.deepEqual(순서, [...순서].sort());
});

test("기한에 걸린 근거 조문은 모두 조문 목록에 있다", () => {
  const 목록 = [
    ...계산(대출사기, { 구술신청일: "2026-10-02", 추가기한통지일: "2026-10-08", 공고일: "2026-10-16", 고소일: "2026-10-05", 불기소통지일: "2026-10-01", 항고기각통지일: "2026-11-02", 범인안날: "2026-10-01" }, { 친족: "예" }),
    ...계산(거래사기, { 불송치통지일: "2026-10-07", 불기소통지일: "2026-10-07" }),
  ];
  for (const k of 목록) for (const id of k.근거) assert.ok(조문[id], `${k.id}: ${id}`);
});

test("기한 문구에 엠대시와 가운뎃점이 없다", () => {
  const 목록 = 계산(대출사기, { 구술신청일: "2026-10-02", 공고일: "2026-10-16", 고소일: "2026-10-05", 불송치통지일: "2026-10-07", 범인안날: "2026-10-01" }, { 친족: "예" });
  const 글 = 목록.flatMap((k) => [k.이름, ...k.계산, ...k.메모]).join("\n");
  assert.doesNotMatch(글, /[—·]/);
});
