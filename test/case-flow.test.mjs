import test from "node:test";
import assert from "node:assert/strict";
import { 질문, 유형확인 } from "../src/engine/classify.mjs";
import { 할일목록 } from "../src/engine/checklist.mjs";
import { 은행단계, 수사단계 } from "../src/engine/stages.mjs";
import { 새사건, 불러오기, 저장하기, 풀이, 판 } from "../src/engine/case.mjs";
import { 조문 } from "../src/engine/law.mjs";

test("물건값으로 보낸 돈은 거래사기이고 지급정지 대상이 아니다", () => {
  const r = 유형확인({ 까닭: "물건", 방법: "계좌" });
  assert.equal(r.유형, "거래사기");
  assert.equal(r.지급정지, false);
  assert.deepEqual(r.근거, ["통신사기법-2-2"]);
});

test("대출을 미끼로 계좌로 보낸 돈은 보이스피싱이고 지급정지를 신청할 수 있다", () => {
  const r = 유형확인({ 까닭: "대출", 방법: "계좌" });
  assert.equal(r.유형, "보이스피싱");
  assert.equal(r.지급정지, true);
});

test("기관 사칭에 현금을 건넸으면 보이스피싱이지만 지급정지는 없다", () => {
  const r = 유형확인({ 까닭: "요구", 방법: "현금" });
  assert.equal(r.유형, "보이스피싱");
  assert.equal(r.지급정지, false);
});

test("투자 사기와 가상자산은 아직 다루지 않는다고 밝힌다", () => {
  assert.equal(유형확인({ 까닭: "투자", 방법: "계좌" }).유형, "범위밖");
  assert.equal(유형확인({ 까닭: "대출", 방법: "가상자산" }).유형, "범위밖");
  assert.equal(유형확인({ 까닭: "기타", 방법: "계좌" }).유형, "범위밖");
  assert.equal(유형확인({ 까닭: "대출" }).유형, null);
});

test("질문의 선택지 값은 겹치지 않는다", () => {
  for (const q of 질문) {
    const 값 = q.선택지.map(([v]) => v);
    assert.equal(new Set(값).size, 값.length, q.id);
  }
});

test("할 일은 유형마다 다르고, 친족이면 고소 기간 항목이 붙는다", () => {
  const 계좌 = 할일목록(유형확인({ 까닭: "대출", 방법: "계좌" }));
  assert.equal(계좌[0].id, "지급정지");
  const 현금 = 할일목록(유형확인({ 까닭: "요구", 방법: "현금" }));
  assert.ok(!현금.some((x) => x.id === "지급정지"));
  const 거래 = 할일목록(유형확인({ 까닭: "물건", 방법: "간편" }), { 친족: "예" });
  assert.ok(거래.some((x) => x.id === "친족고소"));
  assert.equal(거래.at(-1).id, "회복사기");
  assert.deepEqual(할일목록(유형확인({ 까닭: "투자", 방법: "계좌" })), []);
});

test("할 일에 걸린 근거 조문은 모두 조문 목록에 있고, 한 목록 안에서 id 가 겹치지 않는다", () => {
  for (const 답 of [{ 까닭: "대출", 방법: "계좌" }, { 까닭: "요구", 방법: "현금" }, { 까닭: "물건", 방법: "계좌" }]) {
    const 목록 = 할일목록(유형확인(답), { 친족: "예" });
    assert.equal(new Set(목록.map((x) => x.id)).size, 목록.length);
    for (const x of 목록) for (const id of x.근거) assert.ok(조문[id], id);
  }
});

test("은행 단계: 공고일이 지나기 전에는 공고 단계가 예정이다", () => {
  const 전 = 은행단계({ 구술신청일: "2026-10-02", 공고일: "2026-10-16" }, "2026-10-09");
  assert.equal(전.find((s) => s.이름 === "채권소멸 공고").상태, "예정");
  const 후 = 은행단계({ 구술신청일: "2026-10-02", 서면제출일: "2026-10-06", 공고일: "2026-10-16" }, "2026-11-01");
  assert.deepEqual(후.map((s) => s.상태), ["완료", "완료", "지금", "예정"]);
  const 끝 = 은행단계({ 구술신청일: "2026-10-02", 서면제출일: "2026-10-06", 공고일: "2026-10-16" }, "2027-01-04");
  assert.deepEqual(끝.map((s) => s.상태), ["완료", "완료", "완료", "완료"]);
});

test("은행 단계: 날짜 없이 지금인 단계는 하나만 남는다", () => {
  const s = 은행단계({}, "2026-10-09");
  assert.equal(s.filter((x) => x.상태 === "지금").length, 1);
  assert.equal(s[0].상태, "지금");
});

test("수사 단계는 불송치, 송치 뒤 기소, 송치 뒤 불기소로 갈린다", () => {
  assert.equal(수사단계({}).at(-1).이름, "송치 또는 불송치 통지");
  assert.equal(수사단계({ 고소일: "2026-10-05", 불송치통지일: "2026-10-07" }).at(-1).이름, "이의신청");
  assert.equal(수사단계({ 고소일: "2026-10-05", 송치통지일: "2026-11-02", 기소일: "2026-12-01" }).at(-1).이름, "재판");
  const 불기소 = 수사단계({ 고소일: "2026-10-05", 송치통지일: "2026-11-02", 불기소통지일: "2026-12-01", 항고기각통지일: "2027-01-05" });
  assert.equal(불기소.at(-1).이름, "재정신청");
});

test("사건을 저장했다가 다시 읽으면 같다", () => {
  const s = 새사건("2026-10-09");
  s.답 = { 까닭: "물건", 방법: "간편", 친족: "아니오" };
  s.날짜 = { 송금일: "2026-10-03", 고소일: "2026-10-05" };
  s.기록 = [{ id: "e1", 일시: "2026-10-03T14:05", 종류: "대화", 내용: "35만원", 보낸이: "판매자", 금액: 350000, 계좌: null, 출처: "talk.txt 4번째 줄", 상태: "확정" }];
  s.한일 = ["증거"];
  const r = 불러오기(저장하기(s), "2026-10-10");
  assert.equal(r.문제, null);
  assert.deepEqual(r.사건, s);
});

test("망가진 저장 값과 모르는 값은 버린다", () => {
  assert.match(불러오기("{", "2026-10-09").문제, /읽지 못해/);
  assert.match(불러오기(JSON.stringify({ 판: 판 + 1 }), "2026-10-09").문제, /더 새로운 판/);
  const r = 불러오기(JSON.stringify({ 판, 답: { 까닭: "모름", 방법: "계좌" }, 날짜: { 고소일: "2026-02-30", 송금일: "2026-10-03", 엉뚱: "2026-10-03" }, 기록: [null, { id: 1 }], 한일: ["a", "a", 3] }), "2026-10-09");
  assert.deepEqual(r.사건.답, { 방법: "계좌" });
  assert.deepEqual(r.사건.날짜, { 송금일: "2026-10-03" });
  assert.deepEqual(r.사건.기록, []);
  assert.deepEqual(r.사건.한일, ["a"]);
});

test("풀이는 유형에 맞는 기한, 할 일, 단계를 함께 낸다", () => {
  const s = 새사건("2026-10-09");
  s.답 = { 까닭: "대출", 방법: "계좌", 친족: "아니오" };
  s.날짜 = { 구술신청일: "2026-10-09" };
  const p = 풀이(s, "2026-10-09");
  assert.equal(p.다음.id, "서면신청");
  assert.equal(p.다음.날짜, "2026-10-14"); // 한글날, 토요일, 일요일을 건너뛴다
  assert.equal(p.은행.length, 4);
  assert.ok(p.수사.length >= 2);
  const 거래 = 풀이({ ...s, 답: { 까닭: "물건", 방법: "계좌" } }, "2026-10-09");
  assert.deepEqual(거래.은행, []);
});
