test("증거 목록에는 확정한 기록만 시간순으로 들어간다", () => {
  const 기록 = [
    직접기록({ 일시: "2026-10-03T14:10", 종류: "송금", 내용: "물건값", 금액: 350000, 계좌: { 은행: "국민은행", 번호: "123456-01-234567" } }),
    { ...직접기록({ 일시: "2026-10-03T14:00", 종류: "대화", 내용: "판매 글" }), 보낸이: "판매자" },
    { ...직접기록({ 일시: "2026-10-02T10:00", 종류: "기타", 내용: "확인 전" }), 상태: "확인 필요" },
  ];
  assert.deepEqual(시간순(기록).map((x) => x.일시.slice(11)), ["10:00", "14:00", "14:10"]);
  const 경찰 = 증거목록(기록, "경찰", "거래사기");
  assert.deepEqual(경찰.항목.map((x) => x.일시), ["2026-10-03T14:00", "2026-10-03T14:10"]);
  assert.equal(경찰.합계, 350000);
  assert.deepEqual(경찰.상대방, { 이름: ["판매자"], 계좌: ["국민은행 123456-01-234567"] });
  const 은행 = 증거목록(기록, "은행", "보이스피싱");
  assert.equal(은행.항목.length, 1);
  assert.deepEqual(증거목록([], "은행", "보이스피싱").빠진것.length, 1);
  const 대화만 = 증거목록([직접기록({ 일시: "2026-10-03T14:00", 종류: "대화", 내용: "판매 글" })], "은행", "보이스피싱");
  assert.match(대화만.빠진것[0], /송금 기록이 없습니다/);
});

