// 예시 사건. 사람 이름, 회사 이름, 계좌번호는 모두 지어낸 것이다. 날짜는 오늘을 기준으로 정한다.
import { addDays } from "../engine/dates.mjs";
import { 판 } from "../engine/case.mjs";
import { 카톡읽기, 거래내역읽기, 대화를기록으로, 거래를기록으로 } from "../engine/evidence.mjs";

function 대화줄(날, 시각, 이름, 글) {
  const [y, m, d] = 날.split("-").map(Number);
  const [시, 분] = 시각.split(":").map(Number);
  const 열두 = 시 % 12 === 0 ? 12 : 시 % 12;
  return `${y}년 ${m}월 ${d}일 ${시 >= 12 ? "오후" : "오전"} ${열두}:${String(분).padStart(2, "0")}, ${이름} : ${글}`;
}

const 거래줄 = (날, 시각, 금액, 받는분) => `${날.replaceAll("-", ".")} ${시각}:12,모바일이체,"${금액.toLocaleString("ko-KR")}",0,"3,450,000",${받는분}`;
const 거래머리 = "거래일시,적요,출금액(원),입금액(원),잔액(원),받는분";

/** 확인 필요로 남겨 둘 기록 하나만 빼고 확정한다. 확정하는 흐름을 보여 주려는 것이다. */
function 확정(기록, 남길내용) {
  return 기록.map((r) => (r.내용.includes(남길내용) ? r : { ...r, 상태: "확정" }));
}

/**
 * @param {"대출" | "중고거래"} 종류
 * @param {string} 오늘
 */
export function 예시사건(종류, 오늘) {
  const 전 = (n) => addDays(오늘, -n);
  if (종류 === "대출") {
    const 상담 = "예시저축은행 상담원";
    const 대화 = [
      "예시저축은행 상담원님과 카카오톡 대화",
      `저장한 날짜 : ${오늘} 09:00:00`,
      "",
      대화줄(전(2), "10:12", 상담, "안녕하세요. 정부지원 저금리 대환대출 상담 도와드리겠습니다"),
      대화줄(전(2), "10:15", "나", "3천만원 정도 가능할까요"),
      대화줄(전(2), "10:31", 상담, "기존 대출을 먼저 상환하셔야 승인이 납니다. 상환금 1,200,000원을 지정 계좌로 입금해 주세요"),
      대화줄(전(2), "10:32", 상담, "신한 110-123-456789 예시캐피탈"),
      대화줄(전(1), "09:40", "나", "입금했습니다"),
      대화줄(전(1), "09:52", 상담, "확인 후 연락드리겠습니다"),
    ].join("\n");
    const 거래 = 거래내역읽기([거래머리, 거래줄(전(1), "09:38", 1200000, "예시캐피탈 신한 110-123-456789")].join("\n")).거래;
    return {
      판, 만든날: 오늘, 이름: "대출 사기 예시", 내이름: "나",
      답: { 까닭: "대출", 방법: "계좌", 친족: "아니오" },
      날짜: { 송금일: 전(1), 구술신청일: 전(1) },
      기록: 확정([...대화를기록으로(카톡읽기(대화), "예시-대화.txt"), ...거래를기록으로(거래, "예시-거래내역.csv")], "상환금"),
      한일: ["지급정지"],
    };
  }
  const 송금 = 전(96);
  const 판매자 = "판매자";
  const 대화 = [
    "판매자님과 카카오톡 대화",
    `저장한 날짜 : ${오늘} 09:00:00`,
    "",
    대화줄(addDays(송금, -1), "14:05", 판매자, "아이패드 프로 11 미개봉 45만원입니다"),
    대화줄(addDays(송금, -1), "14:07", "나", "직거래 가능할까요"),
    대화줄(addDays(송금, -1), "14:09", 판매자, "지방이라 택배만 됩니다. 입금 확인 후 바로 보내드려요"),
    대화줄(송금, "10:20", 판매자, "카카오뱅크 3333-12-3456789 김예시"),
    대화줄(송금, "10:25", "나", "450,000원 보냈습니다"),
    대화줄(addDays(송금, 2), "19:30", "나", "송장번호 알려주세요"),
    대화줄(addDays(송금, 3), "09:10", "나", "연락 부탁드립니다"),
  ].join("\n");
  const 거래 = 거래내역읽기([거래머리, 거래줄(송금, "10:24", 450000, "김예시 카카오뱅크 3333-12-3456789")].join("\n")).거래;
  return {
    판, 만든날: 오늘, 이름: "중고거래 사기 예시", 내이름: "나",
    답: { 까닭: "물건", 방법: "계좌", 친족: "아니오" },
    날짜: { 송금일: 송금, 고소일: 전(90), 불송치통지일: 전(3) },
    기록: 확정([...대화를기록으로(카톡읽기(대화), "예시-대화.txt"), ...거래를기록으로(거래, "예시-거래내역.csv")], "보냈습니다"),
    한일: ["증거", "플랫폼", "고소"],
  };
}
