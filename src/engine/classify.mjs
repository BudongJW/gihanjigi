/**
 * @param {Record<string, string>} 답
 * @returns {{ 유형: "보이스피싱" | "거래사기" | "범위밖" | null, 이름: string, 지급정지: boolean, 까닭: string[], 근거: string[] }}
 */
export function 유형확인(답 = {}) {
  const { 까닭, 방법 } = 답;
  if (!까닭 || !방법) return { 유형: null, 이름: "아직 고르지 않음", 지급정지: false, 까닭: [], 근거: [] };

  if (까닭 === "투자" || 방법 === "가상자산") {
    return {
      유형: "범위밖", 이름: "시제품이 아직 다루지 않는 유형", 지급정지: false,
      까닭: [까닭 === "투자" ? "투자 사기(리딩방 등)는 2027년에 넣을 예정입니다." : "가상자산 송금은 절차가 달라 아직 다루지 않습니다.", "경찰(112)과 금융감독원(1332) 상담을 먼저 받습니다."],
      근거: [],
    };
  }

  if (까닭 === "물건") {
    return {
      유형: "거래사기", 이름: "물건이나 서비스 거래를 가장한 사기", 지급정지: false,
      까닭: [
        "물건값으로 보낸 돈은 통신사기피해환급법의 지급정지와 피해환급 대상에서 빠집니다.",
        "고소, 거래 플랫폼 보상, 배상명령, 민사 절차로 돈을 되찾습니다.",
        "대가를 주고받는 거래가 아니었다면 다른 절차가 열릴 수 있습니다. 법률구조공단(132)에 확인합니다.",
      ],
      근거: ["통신사기법-2-2"],
    };
  }

  if (까닭 === "대출" || 까닭 === "요구") {
    const 계좌로 = 방법 === "계좌" || 방법 === "간편";
    return {
      유형: "보이스피싱", 이름: "전기통신금융사기(보이스피싱)", 지급정지: 계좌로,
      까닭: [
        까닭 === "대출" ? "대출을 가장한 행위는 전기통신금융사기에 들어갑니다." : "기관이나 지인을 사칭해 돈을 보내게 한 경우입니다.",
        계좌로 ? "계좌로 보낸 돈은 은행에 지급정지와 피해구제를 신청할 수 있습니다." : "현금이나 상품권으로 건넨 돈은 지급정지할 계좌가 없습니다. 경찰 신고가 먼저입니다.",
      ],
      근거: ["통신사기법-2-2", "통신사기법-3"],
    };
  }

  return {
    유형: "범위밖", 이름: "시제품이 아직 다루지 않는 유형", 지급정지: false,
    까닭: ["고른 조건에 맞는 절차가 아직 없습니다.", "경찰(112)과 금융감독원(1332) 상담을 먼저 받습니다."],
    근거: [],
  };
}
