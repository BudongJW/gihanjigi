test("75옥텟이 넘는 줄은 한글 글자를 가르지 않고 접는다", () => {
  const 긴줄 = `DESCRIPTION:${"가".repeat(60)}`;
  const 접은 = 줄접기(긴줄);
  const 줄들 = 접은.split("\r\n");
  assert.ok(줄들.length > 1);
  for (const [i, 줄] of 줄들.entries()) {
    assert.ok(new TextEncoder().encode(줄).length <= 75, `${i}번째 줄이 길다`);
    if (i > 0) assert.equal(줄[0], " ");
  }
  assert.equal(줄들.map((l, i) => (i ? l.slice(1) : l)).join(""), 긴줄);
});

test("달력 파일에는 앞으로 남은 마감과 가능일만 들어가고, 지난 알림은 빠진다", () => {
  const 유형 = 유형확인({ 까닭: "대출", 방법: "계좌" });
  const 기한 = 기한계산(유형, { 구술신청일: "2026-10-02", 공고일: "2026-10-16", 고소일: "2026-10-05", 불송치통지일: "2026-10-07" }, {}, "2026-10-09");
  const { 내용, 개수 } = 일정파일(기한, { 오늘: "2026-10-09", 만든시각: new Date("2026-10-09T01:02:03Z") });
  assert.equal(개수, 1); // 서면신청은 지났고, 채권소멸과 환급결정은 예상일이다
  assert.ok(내용.startsWith("BEGIN:VCALENDAR\r\n"));
  assert.ok(내용.endsWith("END:VCALENDAR\r\n"));
  assert.match(내용, /DTSTART;VALUE=DATE:20270107\r\n/);
  assert.match(내용, /DTEND;VALUE=DATE:20270108\r\n/);
  assert.match(내용, /DTSTAMP:20261009T010203Z/);
  assert.equal((내용.match(/BEGIN:VALARM/g) ?? []).length, 3);
  assert.doesNotMatch(내용, /(?<!\r)\n/, "CRLF 가 아닌 줄 끝이 있다");

  const 가까운 = 일정파일(기한, { 오늘: "2027-01-01", 만든시각: new Date("2027-01-01T00:00:00Z") }).내용;
  assert.deepEqual([...가까운.matchAll(/TRIGGER:(\S+)/g)].map((m) => m[1]), ["-PT15H"]); // 하루 전 오전 9시
});
