// 진행 현황. 이용자가 넣은 통지 날짜로 은행 피해구제와 수사의 단계를 정한다.
// 기관과 연동하기 전에는 이용자가 넣은 날짜만 믿는다.
import { addDays, endOfMonthPeriod, endOfDayPeriod, isIso } from "./dates.mjs";

/** @typedef {{ 이름: string, 상태: "완료" | "지금" | "예정" | "해당 없음", 날짜: string | null, 설명: string }} 단계 */

const 단계 = (이름, 상태, 날짜 = null, 설명 = "") => ({ 이름, 상태, 날짜, 설명 });

/** 은행 피해구제 단계. 계좌로 보낸 보이스피싱일 때만 있다. */
export function 은행단계(events, 오늘) {
  const e = Object.fromEntries(Object.entries(events ?? {}).filter(([, v]) => isIso(v)));
  const 소멸 = e.공고일 ? addDays(endOfMonthPeriod(e.공고일, 2).end, 1) : null;
  const 결정 = 소멸 ? endOfDayPeriod(소멸, 14).end : null;
  const 목록 = [
    단계("지급정지 요청", e.구술신청일 ? "완료" : "지금", e.구술신청일 ?? null, "돈을 보낸 은행이나 112"),
    단계("서면 신청서 제출", e.서면제출일 ? "완료" : e.구술신청일 ? "지금" : "예정", e.서면제출일 ?? null, "전화 신청 뒤 3영업일 안"),
    단계("채권소멸 공고", e.공고일 ? (오늘 < e.공고일 ? "예정" : 오늘 < 소멸 ? "지금" : "완료") : "예정", e.공고일 ?? null, "공고일부터 2개월 뒤 채권 소멸"),
    단계("환급액 결정", 결정 ? (오늘 > 결정 ? "완료" : 오늘 >= 소멸 ? "지금" : "예정") : "예정", 결정, "소멸 뒤 14일 안, 금융감독원"),
  ];
  return 바로잡기(목록);
}

/** 수사 단계. 결과 통지에 따라 갈래가 나뉜다. */
export function 수사단계(events) {
  const e = Object.fromEntries(Object.entries(events ?? {}).filter(([, v]) => isIso(v)));
  const 목록 = [단계("고소 접수", e.고소일 ? "완료" : "지금", e.고소일 ?? null, "사법경찰관")];
  const 결과 = e.불송치통지일 ? "불송치" : e.송치통지일 ? "송치" : null;
  목록.push(단계("수사 진행", 결과 ? "완료" : e.고소일 ? "지금" : "예정", null, "경찰"));
  if (!결과) {
    목록.push(단계("송치 또는 불송치 통지", "예정", null, "결과를 받으면 기한 화면에 날짜를 넣습니다."));
    return 목록;
  }
  if (결과 === "불송치") {
    목록.push(단계("불송치 통지", "완료", e.불송치통지일, "통지 받은 날부터 3개월 안 이의신청"));
    목록.push(단계("이의신청", e.이의신청일 ? "완료" : "지금", e.이의신청일 ?? null, "경찰서장에게"));
    if (e.이의신청일) 목록.push(단계("공소청 송부와 검토", "지금", null, "이의신청이 있으면 사건이 공소청으로 넘어갑니다."));
    return 목록;
  }
  목록.push(단계("송치 통지", "완료", e.송치통지일, "사건이 공소청으로 넘어갔습니다."));
  if (e.기소일) {
    목록.push(단계("기소", "완료", e.기소일, "재판이 열리면 배상명령을 신청할 수 있습니다."));
    목록.push(단계("재판", "지금", null, "변론이 끝나기 전까지 배상명령 신청"));
  } else if (e.불기소통지일) {
    목록.push(단계("불기소 통지", "완료", e.불기소통지일, "통지 받은 날부터 30일 안 항고"));
    목록.push(단계("항고", e.항고기각통지일 ? "완료" : "지금", null, "지방공소청을 거쳐 광역공소청장에게"));
    if (e.항고기각통지일) 목록.push(단계("재정신청", "지금", null, "기각 통지 받은 날부터 10일 안"));
  } else {
    목록.push(단계("공소청 처분", "지금", null, "기소 또는 불기소. 형사사법포털이나 공소청 민원실에서 확인합니다."));
  }
  return 목록;
}

/** 날짜 없이 "지금" 인 단계가 둘 이상이면 앞의 것만 남긴다. 날짜가 있는 단계는 실제로 일어난 일이라 그대로 둔다. */
function 바로잡기(목록) {
  let 지금본 = false;
  return 목록.map((s) => {
    if (s.상태 !== "지금") return s;
    if (지금본 && !s.날짜) return { ...s, 상태: "예정" };
    지금본 = true;
    return s;
  });
}
