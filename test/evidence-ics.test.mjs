test("금액과 계좌 후보를 찾는다", () => {
  assert.deepEqual(금액찾기("350,000원 보내 주세요"), [350000]);
  assert.deepEqual(금액찾기("1,200만원 대출"), [12000000]);
  assert.deepEqual(금액찾기("₩350,000 입금"), [350000]);
  assert.deepEqual(금액찾기("35만원"), [350000]);
  assert.deepEqual(금액찾기("3만5천원"), [35000]);
  assert.deepEqual(금액찾기("배송비 5천원"), [5000]);
  assert.deepEqual(금액찾기("내일 3시"), []);
  assert.deepEqual(계좌찾기("국민 123456-01-234567"), [{ 은행: "국민은행", 번호: "123456-01-234567" }]);
  assert.deepEqual(계좌찾기("카카오뱅크 3333-01-1234567"), [{ 은행: "카카오뱅크", 번호: "3333-01-1234567" }]);
  assert.deepEqual(계좌찾기("010-1234-5678"), []);
});

